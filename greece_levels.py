"""Authored Greek campaign levels 05–08, using the existing movement rules."""
from dataclasses import dataclass


@dataclass(frozen=True)
class GreekLevel:
    ID: int
    TITLE: str
    LENGTH: int
    FLOORS: tuple
    LEDGES: tuple
    CHECKPOINTS: tuple
    MEDALLION: tuple
    BEETLES: tuple
    VULTURES: tuple = ()
    SCORPIONS: tuple = ()
    GYROSPHERES: tuple = ()
    SPIKED: tuple = ()
    CROCODILES: tuple = ()
    VASES: tuple = ()
    START: tuple = (160., 620.)
    HOPLITES: tuple = ()

    def build(self, platform_type, exit_margin=96):
        floors = [platform_type(a, y, b-a, 760-y, True, kind='greek_floor')
                  for a, b, y in self.FLOORS]
        last = floors[-1]
        last.w += exit_margin+32
        ledges = [platform_type(x, y, w, 32, spiked=x in self.SPIKED)
                  for x, y, w in self.LEDGES]
        if self.ID == 7:
            floors.append(platform_type(0, -200, self.LENGTH+128, 310, True, kind='greek_ceiling'))
        gems = [(x+w*f, y-42) for x, y, w in self.LEDGES for f in (.28, .70)]
        gems += [(x, y-48) for a, b, y in self.FLOORS
                 for x in range(a+180, b-80, 480)]
        return floors+ledges, gems

    def floor_height(self, x):
        return next((y for a, b, y in reversed(self.FLOORS) if a <= x), 620)


